// The review gallery: every generator across many seeds, plus the logo at
// 16/32/180/512 px. Self-contained HTML (no fonts, scripts or links), built
// deterministically so the committed art/gallery.html can be checked fresh.

import { createHash } from "node:crypto";
import { seal, iconSvg, lessonScene, portrait, stamp, sceneChoice, TEMPLATE_NAMES } from "../index.mjs";
import { PAPER, INK, CANDIES, TINTS } from "../palette.mjs";
import { esc } from "./svg.mjs";

/** The four real lessons (content/lessons/*.json) and their trait colours. */
export const REAL_LESSONS = [
  { id: "own-your-exit", color: "#18C8F0", title: "Own Your Exit" },
  { id: "friend-speech", color: "#FF1FC8", title: "Manners Make Strangers Safe" },
  { id: "vote-with-your-feet", color: "#5CF27E", title: "Vote With Your Feet" },
  { id: "what-lasts", color: "#FFE11A", title: "What Lasts" },
];

/** Twenty more lesson ids, chosen so every template appears twice. */
export function sampleLessons(count = 20) {
  const per = Math.ceil(count / TEMPLATE_NAMES.length);
  const seen = Object.fromEntries(TEMPLATE_NAMES.map((t) => [t, 0]));
  const out = [];
  for (let i = 0; out.length < count && i < 10000; i++) {
    const id = `sample-${i}`;
    const { template } = sceneChoice(id);
    if (seen[template] >= per) continue;
    seen[template]++;
    // one in five uses a non-candy trait colour, as a new trait might
    const color = out.length % 5 === 4 ? ["#B48CFF", "#FF9F45"][(out.length / 5) % 2 | 0] : CANDIES[out.length % 4];
    out.push({ id, color });
  }
  return out;
}

/** Stamp inputs: two per founding trait, seeds from sha256 (as the chain would derive them). */
export function sampleStamps() {
  const traits = [
    ["SOVEREIGN", "#18C8F0", 0],
    ["CIVIL", "#FF1FC8", 1],
    ["MOBILE", "#5CF27E", 2],
    ["ENDURING", "#FFE11A", 3],
  ];
  const out = [];
  for (let i = 0; i < 8; i++) {
    const [name, color, emblem] = traits[i % 4];
    const seed = "0x" + createHash("sha256").update(`gallery-stamp-${i}`).digest("hex");
    out.push({ seed, name, color, emblem, serial: 1 + i * 37 });
  }
  return out;
}

