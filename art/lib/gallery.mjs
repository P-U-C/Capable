const cell = (inner, label) => `<div class="cell">${inner}<small>${esc(label)}</small></div>`;

export function buildGallery() {
  const o = [];
  o.push(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>capable art gallery</title><style>${CSS}</style></head><body><main>`);
  o.push(`<h1>capable: the art grammar</h1><p>Every piece below is generated by <code>art/index.mjs</code> from a seed. Same input, same bytes. Built by <code>node art/bin/gallery.mjs</code>; see docs/ART.md.</p>`);

  // tokens
  o.push(`<section id="tokens"><h2>Tokens</h2><div class="row">`);
  for (const [c, name] of [[PAPER, "paper"], [INK, "ink"], [CANDIES[0], "cyan"], [CANDIES[1], "magenta"], [CANDIES[2], "lime"], [CANDIES[3], "yellow"], ...TINTS.map((t, i) => [t, ["surface", "slate", "lilac", "blush", "sky"][i]])]) {
    o.push(cell(`<div class="swatch" style="background:${c}"></div>`, `${name} ${c}`));
  }
  o.push(`</div></section>`);

  // logo
  o.push(`<section id="logo"><h2>Seal: the logo</h2><div class="row">`);
  for (const s of [512, 180, 32, 16]) o.push(cell(seal({ mode: "logo", size: s }), `logo ${s}px`));
  o.push(`</div><div class="row" style="margin-top:18px">`);
  for (const s of [180, 64, 32]) o.push(cell(seal({ mode: "lockup", size: s }), `lockup ${s}px tall`));
  o.push(`</div><p style="margin-top:18px">With <code>filled</code>: the ring fills in as traits are earned.</p><div class="row">`);
  const order = ["sovereign", "civil", "mobile", "enduring"];
  for (let k = 0; k <= 4; k++) o.push(cell(seal({ mode: "logo", size: 120, filled: order.slice(0, k) }), k ? order.slice(0, k).join(" + ") : "none yet"));
  o.push(cell(seal({ mode: "lockup", size: 48, filled: ["civil", "enduring"] }), "lockup 48px, civil + enduring"));
  o.push(`</div></section>`);

  // favicon
  o.push(`<section id="favicon"><h2>Favicon</h2><div class="row">`);
  for (const s of [512, 180, 32, 16]) o.push(cell(seal({ mode: "favicon", size: s }), `favicon ${s}px`));
  o.push(`</div><div class="row dark" style="margin-top:18px">`);
  for (const s of [180, 32, 16]) o.push(cell(seal({ mode: "favicon", size: s }), `on ink ${s}px`));
  o.push(`</div></section>`);

  // icons
  o.push(`<section id="icons"><h2>App icons</h2><p>Solid paper square. Maskable keeps the whole seal inside the central 80% circle (dashed).</p><div class="row">`);
  o.push(cell(iconSvg({ size: 192 }), "icon 192"));
  o.push(cell(iconSvg({ size: 180 }), "apple-touch 180"));
  o.push(cell(`<div class="mask">${iconSvg({ size: 256, maskable: true })}</div>`, "maskable (512, shown at 256)"));
  o.push(cell(iconSvg({ size: 48 }), "icon 48"));
  o.push(`</div></section>`);

  // scenes
  const samples = sampleLessons(20);
  o.push(`<section id="scenes"><h2>Lesson scenes</h2><p>The four real lessons first (with their trait colours), then twenty more ids chosen so each of the ${TEMPLATE_NAMES.length} composition templates appears twice. Two-tone riso: trait colour + ink on paper, slate halftone, grain.</p><div class="row">`);
  for (const l of REAL_LESSONS) o.push(cell(`<div class="frame wide">${lessonScene({ lessonId: l.id, color: l.color, title: l.title })}</div>`, `${l.id} · ${sceneChoice(l.id).template}`));
  for (const l of samples) o.push(cell(`<div class="frame wide">${lessonScene({ lessonId: l.id, color: l.color })}</div>`, `${l.id} · ${sceneChoice(l.id).template} · ${l.color}`));
  o.push(`</div><h2 style="font-size:16px">The same scenes in a 9:16 card: the bleed fills the frame</h2><div class="row">`);
  for (const l of REAL_LESSONS) o.push(cell(`<div class="frame tall">${lessonScene({ lessonId: l.id, color: l.color, uid: "tall" })}</div>`, l.id));
  for (const l of samples.slice(0, 2)) o.push(cell(`<div class="frame tall">${lessonScene({ lessonId: l.id, color: l.color, uid: "tall" })}</div>`, l.id));
  o.push(`</div></section>`);

  // portraits
  o.push(`<section id="portraits"><h2>Portraits</h2><p>24 seeds (fids and local ids) at passport size, then the same seeds as 48px avatars. The last four pass a trait colour for the garment.</p><div class="row">`);
  const seeds = [];
  for (let i = 0; i < 20; i++) seeds.push({ seed: String(1000 + i * 7919) });
  for (let i = 0; i < 4; i++) seeds.push({ seed: `local-${i}`, color: CANDIES[i] });
  for (const s of seeds) o.push(cell(`<div class="frame pt">${portrait(s)}</div>`, s.color ? `${s.seed} · ${s.color}` : s.seed));
  o.push(`</div><div class="row" style="margin-top:18px">`);
  for (const s of seeds) o.push(`<div class="frame av">${portrait({ ...s, uid: "av" })}</div>`);
  o.push(`</div></section>`);

  // stamps
  o.push(`<section id="stamps"><h2>Stamps</h2><p><code>stamp</code> is <code>contract/badge-art.mjs</code> badgeSvg, unchanged: the on-chain art.</p><div class="row st">`);
  for (const s of sampleStamps()) o.push(cell(stamp(s), `${s.name} #${s.serial}`));
  o.push(`</div></section>`);

  o.push(`</main></body></html>\n`);
  return o.join("\n");
}
